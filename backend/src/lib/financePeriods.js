/**
 * The period engine: turning a council's financial year into labelled reporting buckets.
 *
 * WHAT THIS IS FOR. Nine of the system's reports are a single annual slice. A Director of Finance's
 * core statutory output is not: monthly management accounts, a quarterly return to the parent
 * Ministry, an annual budget-execution statement. All three are the same figures bucketed by
 * period, so the bucketing is one function here rather than a `date_trunc` written again in each
 * report (design spec §2, decision A3). One place decides what "Q2" means, so a monthly management
 * account and a quarterly return cannot disagree about which month a transaction fell in.
 *
 * PROVENANCE. Adapted from ERPNext's `get_period_list()`
 * (~/Downloads/erpnext-develop/erpnext/accounts/report/financial_statements.py:217-307) and its
 * `get_label()` (`:347-356`). What is taken is the loop: walk from the year start, add the
 * periodicity's months, subtract a day, clip the last bucket to the year end, and step to the day
 * after. What is not taken is everything around it — no fiscal-year lookup, no company, no
 * `frappe._dict`, and no database access of any kind. This file is pure and has no `require`.
 *
 * WHY THE COUNCIL'S OWN YEAR START GOVERNS THE BUCKETS. `finance.financial_year` carries
 * `start_date` and `end_date` set by Council (migration 188_finance_foundation.sql, constraint
 * `financial_year_dates`); nothing in the schema says a year begins in January. Zimbabwean local
 * authorities have run both calendar and July–June years. If the buckets were generated by calendar
 * quarter, a council on a July–June year would be handed a "Q1" of January to March — a quarter
 * that is three quarters into its own year — and the quarterly return would be wrong in a way
 * nobody would notice until the Ministry asked. So the walk starts at `start_date`, and a July–June
 * year yields Q1 = Jul–Sep.
 *
 * THE PROPERTY EVERYTHING ELSE RESTS ON. In the default (discrete) mode the buckets TILE the year
 * exactly: bucket n+1 begins the day after bucket n ends, the first begins on `start`, the last
 * ends on `end`, and no two overlap. A date in the year therefore falls in exactly one bucket, so
 * a report that sums each bucket has counted every transaction once — none twice, none dropped.
 * `test/finance-periods.test.js` asserts that property day by day, including for a year that is
 * not twelve whole months and a year that does not start on the first of a month.
 *
 * MONEY IS NOT HERE. This file produces dates and labels. The bucket boundaries are passed to SQL
 * as bound parameters and every amount is summed by Postgres over NUMERIC — see the header of
 * src/lib/finance.js for why a period total computed in JavaScript would be the worst defect this
 * workstream could introduce.
 *
 * DAY CLAMPING. `addMonths` clamps to the end of the target month, as ERPNext's `add_months` does:
 * 31 January plus one month is 28 February. A year starting on the 31st therefore produces buckets
 * whose start day drifts earlier after a short month. The tiling property is unaffected — every
 * bucket still begins the day after the previous one ended — and this is noted rather than fixed
 * because any other rule either overlaps buckets or leaves a gap.
 */

/** The periodicities a report may be run at, and how many months each bucket spans. */
const PERIODICITY_MONTHS = {
  monthly: 1,
  quarterly: 3,
  half_yearly: 6,
  yearly: 12,
}

const PERIODICITIES = Object.keys(PERIODICITY_MONTHS)

/** The letter each periodicity's key begins with: 'm01', 'q1', 'h1', 'y1'. */
const KEY_PREFIX = { monthly: 'm', quarterly: 'q', half_yearly: 'h', yearly: 'y' }

const MONTH_NAMES = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun',
  'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']

/**
 * A bucket key, as a SQL alias and an object key.
 *
 * Keys are generated here from a counter, never from anything a caller supplied, but the pattern is
 * asserted anyway by `assertPeriodKey()` below: a report composes this string into a SELECT list as
 * a column alias, and "the value cannot reach here" is a claim worth being able to check rather
 * than a convention.
 */
const KEY_PATTERN = /^[mqhy]\d{1,3}$/

/** True for a key this module could have produced. Any identifier built into SQL is checked. */
const isPeriodKey = (key) => typeof key === 'string' && KEY_PATTERN.test(key)

/** Throw unless `key` is one of this module's keys. Called before a key becomes a SQL alias. */
function assertPeriodKey(key) {
  if (!isPeriodKey(key)) {
    throw new Error(`financePeriods: ${JSON.stringify(key)} is not a period key and must not be used as a SQL alias`)
  }
  return key
}

const ISO_DATE = /^(\d{4})-(\d{2})-(\d{2})$/

/**
 * Parse 'YYYY-MM-DD' into { y, m, d }, rejecting a date that does not exist.
 *
 * Dates arrive from `finance.financial_year` through `dateText()` (src/lib/finance.js:213), which
 * re-selects a DATE column as text precisely so no time zone is involved. They are kept as plain
 * y/m/d numbers here for the same reason: a JavaScript Date in Central Africa Time turns
 * '2031-01-01' into the previous evening in UTC, and a financial year that appears to start before
 * it does is how an off-by-one-day bucket gets shipped.
 */
function parseIsoDate(value, what) {
  const match = ISO_DATE.exec(String(value ?? '').slice(0, 10))
  if (!match) throw new Error(`financePeriods: ${what} must be a YYYY-MM-DD date, received ${JSON.stringify(value)}`)
  const y = Number(match[1])
  const m = Number(match[2])
  const d = Number(match[3])
  if (m < 1 || m > 12 || d < 1 || d > daysInMonth(y, m)) {
    throw new Error(`financePeriods: ${what} is not a date that exists (${value})`)
  }
  return { y, m, d }
}

const format = ({ y, m, d }) =>
  `${String(y).padStart(4, '0')}-${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}`

/** Days in a month, Gregorian. February is the only interesting case. */
function daysInMonth(y, m) {
  if (m === 2) return (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0 ? 29 : 28
  return [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31][m - 1]
}

/** Comparison as a single integer, so no Date and no time zone is involved. */
const ordinal = ({ y, m, d }) => y * 10000 + m * 100 + d

/** Add `n` months, clamping the day to the end of the target month (ERPNext `add_months`). */
function addMonths({ y, m, d }, n) {
  const zeroBased = (y * 12 + (m - 1)) + n
  const ny = Math.floor(zeroBased / 12)
  const nm = (zeroBased % 12) + 1
  return { y: ny, m: nm, d: Math.min(d, daysInMonth(ny, nm)) }
}

/** The day before. */
function previousDay({ y, m, d }) {
  if (d > 1) return { y, m, d: d - 1 }
  if (m > 1) return { y, m: m - 1, d: daysInMonth(y, m - 1) }
  return { y: y - 1, m: 12, d: 31 }
}

/** The day after. */
function nextDay({ y, m, d }) {
  if (d < daysInMonth(y, m)) return { y, m, d: d + 1 }
  if (m < 12) return { y, m: m + 1, d: 1 }
  return { y: y + 1, m: 1, d: 1 }
}

const isMonthStart = (p) => p.d === 1
const isMonthEnd = (p) => p.d === daysInMonth(p.y, p.m)
const monthYear = (p) => `${MONTH_NAMES[p.m - 1]} ${p.y}`
const dayMonthYear = (p) => `${p.d} ${MONTH_NAMES[p.m - 1]} ${p.y}`

/**
 * A bucket's human label.
 *
 * The label is what a councillor reads on a column header and what a Ministry reader sees on the
 * cover, so it states the bucket's real extent rather than a tidy approximation. A bucket that
 * covers one whole calendar month is 'Mar 2026'; one that does not — which is what a year starting
 * mid-month produces, and what the clipped final bucket often is — says its days.
 *
 * An accumulated bucket's label says what it accumulates to, which is spec §2's '"To Mar 2026"'.
 */
function labelFor(periodicity, from, to, accumulated) {
  if (accumulated) {
    return isMonthEnd(to) ? `To ${monthYear(to)}` : `To ${dayMonthYear(to)}`
  }
  const whole = isMonthStart(from) && isMonthEnd(to)
  if (!whole) return `${dayMonthYear(from)} - ${dayMonthYear(to)}`
  if (periodicity === 'monthly') return monthYear(from)
  if (periodicity === 'yearly') return from.y === to.y ? `${from.y}` : `${from.y}-${to.y}`
  // Quarterly and half-yearly: 'Jul-Sep 2026' within one calendar year, 'Oct 2026-Mar 2027' across.
  if (from.y === to.y) return `${MONTH_NAMES[from.m - 1]}-${MONTH_NAMES[to.m - 1]} ${from.y}`
  return `${monthYear(from)}-${monthYear(to)}`
}

/**
 * A financial year is at most a little over twelve months. This cap is a guard against a caller
 * passing a decade-long range by mistake, not a supported range: a report with 400 period columns
 * is not a report.
 */
const MAX_BUCKETS = 60

/**
 * Turn a date range and a periodicity into labelled reporting buckets.
 *
 *   periodList({ start: '2026-07-01', end: '2027-06-30', periodicity: 'quarterly' })
 *   // -> [ { from_date: '2026-07-01', to_date: '2026-09-30', key: 'q1', label: 'Jul-Sep 2026' },
 *   //      { from_date: '2026-10-01', to_date: '2026-12-31', key: 'q2', label: 'Oct-Dec 2026' },
 *   //      ... ]
 *
 * `start` and `end` are the council's own `finance.financial_year.start_date` and `end_date` as
 * 'YYYY-MM-DD' text. `periodicity` is one of 'monthly', 'quarterly', 'half_yearly', 'yearly'.
 *
 * `accumulated: true` returns the same `to_date`s with every `from_date` set to the year start, for
 * the year-to-date column set a quarterly return is made of. Those buckets OVERLAP by design — the
 * last one is the whole year — so a caller must not sum them.
 *
 * Throws on an invalid date, an end before the start, or an unknown periodicity. A report would
 * rather fail loudly than print a column set it cannot account for.
 */
function periodList({ start, end, periodicity, accumulated = false }) {
  if (!Object.prototype.hasOwnProperty.call(PERIODICITY_MONTHS, periodicity)) {
    throw new Error(`financePeriods: periodicity must be one of ${PERIODICITIES.join(', ')}, received ${JSON.stringify(periodicity)}`)
  }
  const yearStart = parseIsoDate(start, 'start')
  const yearEnd = parseIsoDate(end, 'end')
  if (ordinal(yearEnd) < ordinal(yearStart)) {
    throw new Error(`financePeriods: end (${end}) is before start (${start})`)
  }

  const step = PERIODICITY_MONTHS[periodicity]
  const prefix = KEY_PREFIX[periodicity]
  const pad = periodicity === 'monthly' ? 2 : 1

  const periods = []
  let cursor = yearStart

  while (ordinal(cursor) <= ordinal(yearEnd)) {
    // The bucket's natural end: `step` months on from its start, less a day. Clipped to the year
    // end, so the final bucket of a year that is not a whole number of periods stops where the
    // council's year stops and never runs past it.
    const natural = previousDay(addMonths(cursor, step))
    const to = ordinal(natural) <= ordinal(yearEnd) ? natural : yearEnd

    const index = periods.length + 1
    const key = assertPeriodKey(`${prefix}${String(index).padStart(pad, '0')}`)
    const from = accumulated ? yearStart : cursor

    periods.push({
      from_date: format(from),
      to_date: format(to),
      key,
      label: labelFor(periodicity, from, to, accumulated),
    })

    if (periods.length > MAX_BUCKETS) {
      throw new Error(`financePeriods: ${start} to ${end} at ${periodicity} would produce more than ${MAX_BUCKETS} periods; that is a range, not a financial year`)
    }
    cursor = nextDay(to)
  }

  return periods
}

/** Does `outer` wholly contain `inner`? ISO dates compare correctly as strings. */
const containsPeriod = (outer, inner) =>
  inner.from_date >= outer.from_date && inner.to_date <= outer.to_date

/**
 * How a budget phasing profile maps onto a report's period columns.
 *
 * A profile (`finance.budget_distribution`, migration 204) records a percentage per period AT ITS
 * OWN PERIODICITY. A report asks for columns at the periodicity the user chose. This works out
 * which profile periodicities can honestly serve that report, and which of a profile's period
 * keys fall inside each report column, so the percentage for a column is a SUM OF RECORDED
 * PERCENTAGES and never a division of one.
 *
 * TWO REFUSALS, BOTH DELIBERATE:
 *
 * 1. A COARSER PROFILE CANNOT SERVE A FINER REPORT. A quarterly profile asked for monthly columns
 *    would have to split each quarter into three months, and nobody approved those three figures.
 *    Such a periodicity is left out of `usablePeriodicities` and the report treats its lines as
 *    having no phasing for that run, rather than inventing a split.
 *
 * 2. A FINER PROFILE MUST NEST EXACTLY. Monthly buckets usually sit three-to-a-quarter, but not
 *    always: on a year starting the 31st, day clamping makes the monthly walk and the quarterly
 *    walk drift apart (see `addMonths` above), and a month can then straddle a quarter boundary.
 *    Summing the months inside such a quarter would quietly drop the straddling one. So nesting is
 *    CHECKED — every profile bucket must fall inside exactly one discrete report bucket — and a
 *    periodicity that fails the check is not usable for that run.
 *
 * Returns:
 *   periods              the report's own columns (accumulated if asked for)
 *   discrete             the same columns in discrete form, which is what nesting is tested against
 *   usablePeriodicities  the profile periodicities that can serve this report
 *   expectedKeys         { periodicity: [key] } — what a profile of each periodicity must hold for
 *                        this financial year, so a caller can reject a profile whose keys do not
 *                        match the year (a profile built for a twelve-month year, attached to a
 *                        nine-month one)
 *   keysByPeriod         { reportColumnKey: [profile period keys inside it] }
 *
 * Pure, like everything else in this file: it reads no database and computes no money.
 */
function distributionPlan({ start, end, periodicity, accumulated = false }) {
  const discrete = periodList({ start, end, periodicity, accumulated: false })
  const periods = accumulated
    ? periodList({ start, end, periodicity, accumulated: true })
    : discrete

  const expectedKeys = {}
  const usablePeriodicities = []
  const profilePeriods = {}

  for (const candidate of PERIODICITIES) {
    const buckets = periodList({ start, end, periodicity: candidate })
    profilePeriods[candidate] = buckets
    expectedKeys[candidate] = buckets.map((b) => b.key)
    if (PERIODICITY_MONTHS[candidate] > PERIODICITY_MONTHS[periodicity]) continue
    const nests = buckets.every(
      (b) => discrete.filter((r) => containsPeriod(r, b)).length === 1,
    )
    if (nests) usablePeriodicities.push(candidate)
  }

  const keysByPeriod = {}
  for (const column of periods) {
    const keys = []
    for (const candidate of usablePeriodicities) {
      for (const bucket of profilePeriods[candidate]) {
        if (containsPeriod(column, bucket)) keys.push(bucket.key)
      }
    }
    keysByPeriod[column.key] = keys
  }

  return { periods, discrete, usablePeriodicities, expectedKeys, keysByPeriod }
}

module.exports = {
  periodList,
  distributionPlan,
  PERIODICITIES,
  PERIODICITY_MONTHS,
  isPeriodKey,
  assertPeriodKey,
}
