/**
 * Walk-into-the-council-building service catalogue.
 * One record per counter a citizen would ask for at reception.
 * `status: live` only when a real UI path exists; otherwise coming_soon.
 */
export type ServiceStatus = 'live' | 'coming_soon'
export type ServiceChannel = 'online' | 'counter' | 'both'

export type CitizenSectionKey =
  | 'dashboard' | 'services' | 'new' | 'applications' | 'map' | 'documents'
  | 'notices' | 'payments' | 'inspections' | 'certificates' | 'appeals'
  | 'profile' | 'reference' | 'complaints' | 'service_desk'

export interface CitizenService {
  id: string
  department: string
  title: string
  askFor: string
  description: string
  documents: string[]
  feeHint: string
  outcome: string
  status: ServiceStatus
  channel: ServiceChannel
  /** Portal section and/or absolute path */
  section?: CitizenSectionKey
  href?: string
  requiresAuth: boolean
  requiresResidency: boolean
}

