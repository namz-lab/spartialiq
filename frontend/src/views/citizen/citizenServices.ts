export function servicesByDepartment() {
  const map = new Map<string, CitizenService[]>()
  for (const s of CITIZEN_SERVICES) {
    const list = map.get(s.department) || []
    list.push(s)
    map.set(s.department, list)
  }
  return [...map.entries()].map(([department, services]) => ({ department, services }))
}

export function liveServices() {
  return CITIZEN_SERVICES.filter(s => s.status === 'live')
}
